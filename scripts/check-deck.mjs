// Validates src/data/questions.json. Runs before every build (npm run build)
// and on its own with: npm run check
// Fails with a list of every problem, each pointing at the card it concerns.
import { readFile } from 'node:fs/promises';

const CARDS_PER_LEVEL = 12;
const LEVELS = ['200', '400', '600'];
const KINDS = ['qa', 'blank', 'emoji', 'charades', 'picture'];
const CATEGORY_FIELDS = ['id', 'name', 'icon', 'kind', 'levels'];
const CARD_FIELDS = ['q', 'a', 'img'];
// House rule: Lebanese content stays in its own opt-in theme.
const LEBANON_THEME = 'levant';
const LEBANON_WORDS = /\b(leban\w*|beirut|levant\w*|byblos|sidon|baalbek|fairuz|rahbani|labaki|man'oushe|kibbeh|labneh|dabke|knafeh|mansaf|tabbouleh|arak)\b/i;

const read = (path) => readFile(new URL(path, import.meta.url), 'utf8');

const errors = [];
const warnings = [];

let deck;
try {
  deck = JSON.parse(await read('../src/data/questions.json'));
} catch (e) {
  console.error(`✗ src/data/questions.json is not valid JSON:\n  ${e.message}`);
  process.exit(1);
}

// Picture keys the app can actually show (generated by npm run images).
const imagesSource = await read('../src/images.ts');
const imageKeys = new Set([...imagesSource.matchAll(/^ {2}"([^"]+)": \{/gm)].map((m) => m[1]));

const isText = (v) => typeof v === 'string' && v.trim() !== '';
const seenIds = new Set();
const seenQuestions = new Map();
const seenImages = new Map();
let cards = 0;

if (!Array.isArray(deck.categories)) errors.push('Top level must be { "categories": [ ... ] }');

for (const [ci, cat] of (deck.categories ?? []).entries()) {
  const where = `category #${ci + 1}${cat.id ? ` (${cat.id})` : ''}`;
  for (const field of Object.keys(cat)) if (!CATEGORY_FIELDS.includes(field)) errors.push(`${where}: unknown field "${field}"`);
  for (const field of ['id', 'name', 'icon']) if (!isText(cat[field])) errors.push(`${where}: "${field}" is missing or empty`);
  if (!KINDS.includes(cat.kind)) errors.push(`${where}: "kind" must be one of ${KINDS.join(', ')}`);
  if (seenIds.has(cat.id)) errors.push(`${where}: id "${cat.id}" is used twice`);
  seenIds.add(cat.id);

  const levels = cat.levels ?? {};
  for (const key of Object.keys(levels)) if (!LEVELS.includes(key)) errors.push(`${where}: unknown level "${key}" (use ${LEVELS.join(', ')})`);

  for (const level of LEVELS) {
    const list = levels[level];
    if (!Array.isArray(list)) { errors.push(`${where}: level "${level}" is missing`); continue; }
    if (list.length !== CARDS_PER_LEVEL) errors.push(`${where} › ${level}: has ${list.length} cards, needs ${CARDS_PER_LEVEL}`);

    for (const [i, card] of list.entries()) {
      cards++;
      const at = `${cat.id} › ${level} › card ${i + 1}${isText(card?.a) ? ` ("${card.a}")` : ''}`;
      if (typeof card !== 'object' || card === null) { errors.push(`${at}: must be an object like { "q": ..., "a": ... }`); continue; }
      for (const field of Object.keys(card)) if (!CARD_FIELDS.includes(field)) errors.push(`${at}: unknown field "${field}"`);
      if (!isText(card.q)) errors.push(`${at}: "q" (question) is missing or empty`);
      if (!isText(card.a)) errors.push(`${at}: "a" (answer) is missing or empty`);

      if (card.img !== undefined) {
        if (!imageKeys.has(card.img)) errors.push(`${at}: picture "${card.img}" not found in src/images.ts — add it to scripts/image-sources.json and run npm run images`);
        if (seenImages.has(card.img)) errors.push(`${at}: picture "${card.img}" is also used by ${seenImages.get(card.img)}`);
        seenImages.set(card.img, at);
      } else if (cat.kind === 'picture') {
        errors.push(`${at}: cards in a picture theme need an "img"`);
      }

      // Picture and charades prompts repeat by design ("Whose flag is this?", "Act it out").
      if (!card.img && cat.kind !== 'charades' && isText(card.q)) {
        const key = card.q.trim().toLowerCase();
        if (seenQuestions.has(key)) errors.push(`${at}: same question as ${seenQuestions.get(key)}`);
        else seenQuestions.set(key, at);
      }

      if (cat.id !== LEBANON_THEME && LEBANON_WORDS.test(`${card.q} ${card.a}`)) {
        warnings.push(`${at}: looks Lebanese — keep those in the "${LEBANON_THEME}" theme`);
      }
    }
  }
}

for (const w of warnings) console.warn(`! ${w}`);
if (errors.length) {
  console.error(`✗ questions.json has ${errors.length} problem${errors.length > 1 ? 's' : ''}:`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}
console.log(`✓ questions.json OK: ${deck.categories.length} themes, ${cards} cards`);
