// Resolves every picture card in scripts/image-sources.json to a free-licensed
// Wikimedia Commons photo and writes src/images.ts (thumbnail URL + credit).
// Run with: npm run images
import { readFile, writeFile } from 'node:fs/promises';

const API = 'https://en.wikipedia.org/w/api.php';
const WIDTH = 800;
const HEADERS = { 'User-Agent': 'khamse-trivia-image-script/1.0 (static party game)' };

const sources = JSON.parse(await readFile(new URL('./image-sources.json', import.meta.url), 'utf8'));
delete sources._comment;

const chunks = (items, n) => Array.from({ length: Math.ceil(items.length / n) }, (_, i) => items.slice(i * n, i * n + n));

async function api(params) {
  const url = `${API}?${new URLSearchParams({ format: 'json', formatversion: '2', ...params })}`;
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  return res.json();
}

// 1. Article title -> lead image file name (free images only).
const articles = Object.values(sources).filter((v) => typeof v === 'string');
const fileForArticle = new Map();
for (const batch of chunks(articles, 50)) {
  const data = await api({ action: 'query', prop: 'pageimages', piprop: 'name', pilicense: 'free', redirects: '1', titles: batch.join('|') });
  const alias = new Map();
  for (const n of data.query.normalized ?? []) alias.set(n.to, n.from);
  for (const r of data.query.redirects ?? []) alias.set(r.to, alias.get(r.from) ?? r.from);
  for (const page of data.query.pages) {
    const original = alias.get(page.title) ?? page.title;
    if (page.pageimage) fileForArticle.set(original, page.pageimage);
  }
}

const fileFor = (src) => (typeof src === 'string' ? fileForArticle.get(src) : src.file);

// 2. File name -> thumbnail URL, page URL and licence/author.
const files = [...new Set(Object.values(sources).map(fileFor).filter(Boolean))];
const info = new Map();
for (const batch of chunks(files, 50)) {
  const data = await api({
    action: 'query', prop: 'imageinfo', iiprop: 'url|extmetadata', iiurlwidth: String(WIDTH),
    titles: batch.map((f) => `File:${f}`).join('|'),
  });
  for (const page of data.query.pages) {
    const ii = page.imageinfo?.[0];
    if (!ii) continue;
    const meta = ii.extmetadata ?? {};
    const strip = (html = '') => html.replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim();
    let author = strip(meta.Artist?.value) || 'Unknown author';
    if (author.length > 60) author = `${author.slice(0, 57)}…`;
    info.set(page.title.replace(/^File:/, ''), {
      src: ii.thumburl ?? ii.url,
      page: ii.descriptionurl,
      credit: `${author} · ${strip(meta.LicenseShortName?.value) || 'see source'}`,
    });
  }
}

// 3. Write the module, reporting anything that could not be resolved.
const out = {};
const missing = [];
for (const [key, src] of Object.entries(sources)) {
  const file = fileFor(src);
  const entry = file && info.get(file.replace(/_/g, ' '));
  if (entry) out[key] = entry;
  else missing.push(`${key} (${typeof src === 'string' ? src : src.file})`);
}

const body = `// Generated by scripts/fetch-images.mjs from scripts/image-sources.json — do not edit by hand.
// Photos are hosted on Wikimedia Commons under the licences named in each credit.

export interface PictureInfo {
  src: string;
  page: string;
  credit: string;
}

export const IMAGES: Record<string, PictureInfo> = ${JSON.stringify(out, null, 2)};
`;
await writeFile(new URL('../src/images.ts', import.meta.url), body);
console.log(`Wrote ${Object.keys(out).length} images to src/images.ts`);
if (missing.length) {
  console.error(`Missing ${missing.length}:\n  ${missing.join('\n  ')}`);
  process.exitCode = 1;
}
